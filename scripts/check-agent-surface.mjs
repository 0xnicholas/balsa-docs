#!/usr/bin/env node
/**
 * The three agent-surface assertions (#26, agent-surface.md §9) — the ones that only hold
 * once the site has been built. All three read `dist/`; the rules live in
 * `src/lib/agent-surface.ts` and are unit-tested there.
 *
 *   ① every HTML route has a `.md` twin (and every twin a page), and every page advertises
 *      its twin in the head — the plugin serves the twins but injects no link (§5.2);
 *   ② the two site-root files agree with the content set: `/llms.txt` links every authored
 *      page exactly once and covers the generated tree as its ten module groups, and
 *      `/llms-manifest.json` says what the tree says (§9.2);
 *   ③ writing rules ①② over the twins: fences carry a language, headings descend one level
 *      at a time under the page title (§6).
 *
 * Usage:
 *   node --experimental-strip-types scripts/check-agent-surface.mjs [--root <dir>] [--dist <dir>]
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs, pinnedRefOf } from './lib/cli.mjs';
import {
	alternateLink,
	apiModuleEntries,
	apiModuleIssues,
	headLinkIssues,
	llmsIndexIssues,
	manifestIssues,
	surfacePages,
	twinIssues,
	writingRuleIssues,
} from '../src/lib/agent-surface.ts';
import { apiTreePageFiles } from '../src/lib/api-tree.ts';
import { site as siteOrigin } from '../src/lib/site.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const { options, errors } = parseArgs(process.argv.slice(2), { values: ['root', 'dist', 'pin'] });

if (errors.length > 0) {
	for (const error of errors) console.error(`✗ ${error}`);
	process.exit(2);
}

const repoRoot = options.root ?? root;
const dist = options.dist ?? path.join(repoRoot, 'dist');

if (!existsSync(dist)) {
	console.error(`✗ ${path.relative(repoRoot, dist)} is missing — \`pnpm build\` writes it before this gate runs`);
	process.exit(1);
}

const failures = [];
const pinned = pinnedRefOf(repoRoot, options);
if (pinned.error) {
	console.error(`✗ ${pinned.error}`);
	process.exit(1);
}

/** `dist`-relative paths, `/`-separated. Only the extensions this gate can reason about. */
const files = walk(dist);
/** The content tree: every route, and the pages the two site-root files describe. */
const { routes, pages, issues } = surfacePages(repoRoot);
failures.push(...issues);
const authored = pages.map((page) => page.route);
const modules = apiModuleEntries();
const read = (file) => readFileSync(path.join(dist, file), 'utf8');

/** ① twins, in both directions, plus the head link that advertises them (§2, §5.2). */
const twin = twinIssues({ routes, files });
const head = headLinkIssues(
	files
		.filter((file) => file.endsWith('.html'))
		.map((file) => ({ path: file, alternate: alternateLink(read(file)) })),
);
failures.push(...twin, ...head);
if (twin.length === 0 && head.length === 0) {
	console.log(
		`✓ twins: ${routes.length} route(s) → \`<route>.md\`, every twin has a page, and every page advertises it in the head`,
	);
}

/** ② the two site-root files agree with the content set (§4, §9.2). */
const llmsFile = 'llms.txt';
const manifestFile = 'llms-manifest.json';
const index = [];
const manifest = [];

if (!files.includes(llmsFile)) {
	index.push(`${llmsFile} is missing from the build output — it is generated by scripts/gen-agent-surface.mjs`);
} else {
	index.push(
		...llmsIndexIssues({
			source: read(llmsFile),
			routes: authored,
			modules,
			files,
			site: siteOrigin,
		}),
	);
}
index.push(...apiModuleIssues({ treeFiles: apiTreePageFiles(repoRoot), modules }));

if (!files.includes(manifestFile)) {
	manifest.push(`${manifestFile} is missing from the build output — it is generated by scripts/gen-agent-surface.mjs`);
} else {
	manifest.push(
		...manifestIssues({ source: read(manifestFile), pages, pin: pinned.pin, site: siteOrigin }),
	);
}

failures.push(...index, ...manifest);
if (index.length === 0 && manifest.length === 0) {
	console.log(
		`✓ index and manifest: /llms.txt lists ${authored.length} page(s) and ${modules.length} module groups — exactly the content set, no dead links; the manifest agrees with the tree`,
	);
}

/** ③ writing rules ①② over the twins — the bytes an agent reads (§6). */
const twins = files.filter((file) => file.endsWith('.md'));
const writing = writingRuleIssues(twins.map((file) => ({ path: file, source: read(file) })));
failures.push(...writing);
if (writing.length === 0) {
	console.log(`✓ writing rules: ${twins.length} twin(s) — every fence carries a language, headings descend one level at a time`);
}

if (failures.length > 0) {
	console.error('');
	for (const failure of failures) console.error(`✗ ${failure}`);
	console.error(`\n${failures.length} agent-surface check(s) failed (agent-surface.md §9).`);
	process.exit(1);
}

console.log('\nAgent surface holds: twins, index and writing rules agree with the content set.');

/**
 * Every `.html` / `.md` / `.json` / `.txt` under the build output, as `/`-separated relative
 * paths — the extensions the assertions look at (pages, twins, and the machine files the
 * index may link).
 */
function walk(directory, prefix = '') {
	const found = [];
	for (const entry of readdirSync(directory, { withFileTypes: true }).sort((left, right) =>
		left.name.localeCompare(right.name),
	)) {
		const relative = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
		if (entry.isDirectory()) found.push(...walk(path.join(directory, entry.name), relative));
		else if (/\.(html|md|json|txt)$/.test(entry.name)) found.push(relative);
	}
	return found;
}
